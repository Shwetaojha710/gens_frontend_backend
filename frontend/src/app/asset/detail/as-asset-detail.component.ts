import { Component, OnInit } from '@angular/core';
import { CommonModule } from '@angular/common';
import { FormsModule } from '@angular/forms';
import { ActivatedRoute, RouterLink } from '@angular/router';
import { DomSanitizer, SafeHtml } from '@angular/platform-browser';
import { NgSelectModule } from '@ng-select/ng-select';
import { Notyf } from 'notyf';
import { AssetService } from '../../services/asset.service';
import { MasterService } from '../../services/master.service';
import {
  CONDITIONS,
  MAINTENANCE_TYPES,
  ackBadge,
  ackLabel,
  conditionBadge,
  conditionLabel,
  eventLabel,
  fmtMoney,
  printLabels,
  statusBadge,
  statusLabel,
} from '../asset-utils';

type Tab = 'history' | 'maintenance' | 'timeline';

/** HR: one asset — holder, return, maintenance & warranty, condition timeline, QR. */
@Component({
  selector: 'app-as-asset-detail',
  standalone: true,
  imports: [CommonModule, FormsModule, RouterLink, NgSelectModule],
  templateUrl: './as-asset-detail.component.html',
})
export class AsAssetDetailComponent implements OnInit {
  private notyf = new Notyf();

  id = '';
  tab: Tab = 'history';
  detail: any = null;
  qr: SafeHtml | null = null;
  saving = false;
  employeeOptions: any[] = [];
  categories: any[] = [];

  editForm: any = null;
  allocateForm: any = null;
  returnForm: any = null;
  maintForm: any = null;
  closeForm: any = null;
  statusForm: any = null;

  readonly conditions = CONDITIONS;
  readonly maintenanceTypes = MAINTENANCE_TYPES;
  readonly fmtMoney = fmtMoney;
  readonly statusLabel = statusLabel;
  readonly statusBadge = statusBadge;
  readonly conditionLabel = conditionLabel;
  readonly conditionBadge = conditionBadge;
  readonly ackLabel = ackLabel;
  readonly ackBadge = ackBadge;
  readonly eventLabel = eventLabel;

  constructor(
    private route: ActivatedRoute,
    private api: AssetService,
    private master: MasterService,
    private sanitizer: DomSanitizer,
  ) {}

  ngOnInit(): void {
    this.master.getemployeeList().subscribe((res: any) => {
      this.employeeOptions = res?.status === true ? res.data.filter((o: any) => o.value && o.value !== 'All') : [];
    });
    this.api.listCategories().subscribe((res: any) => (this.categories = res?.data || []));
    this.route.paramMap.subscribe((p) => {
      this.id = p.get('id') || '';
      this.load();
      this.loadQr();
    });
  }

  get asset(): any { return this.detail?.asset; }
  get current(): any { return this.detail?.allocations?.find((a: any) => a.status === 'active') || null; }
  get openMaintenance(): any { return this.detail?.maintenance?.find((m: any) => m.status === 'open') || null; }
  get today(): string { return new Date().toISOString().slice(0, 10); }

  load(): void {
    this.api.detail(this.id).subscribe((res: any) => {
      if (res?.status !== true) {
        this.notyf.error(res?.message || 'Asset not found');
        return;
      }
      this.detail = res.data;
    });
  }

  private loadQr(): void {
    this.api.labels([this.id], window.location.origin).subscribe((res: any) => {
      // SVG is generated by our backend from a fixed URL + token, so it is safe to render
      const svg = res?.data?.[0]?.svg;
      this.qr = svg ? this.sanitizer.bypassSecurityTrustHtml(svg) : null;
    });
  }

  printLabel(): void {
    const company = JSON.parse(localStorage.getItem('tenant') || '{}')?.companyName || '';
    this.api.labels([this.id], window.location.origin).subscribe((res: any) => {
      if (res?.status === true && !printLabels(res.data, company)) this.notyf.error('Allow pop-ups to print labels');
    });
  }

  private run(obs: any, after: () => void): void {
    this.saving = true;
    obs.subscribe({
      next: (res: any) => {
        this.saving = false;
        if (res?.status === true) {
          this.notyf.success(res.message);
          after();
          this.load();
        } else this.notyf.error(res?.message || 'Request failed');
      },
      error: () => {
        this.saving = false;
        this.notyf.error('Request failed');
      },
    });
  }

  openEdit(): void {
    this.editForm = { ...this.asset, conditionNote: '' };
  }

  saveEdit(): void {
    this.run(this.api.update(this.editForm), () => (this.editForm = null));
  }

  openAllocate(): void {
    this.allocateForm = { assetId: this.id, employeeId: null, allocatedOn: this.today, expectedReturnDate: '', notes: '' };
  }

  saveAllocate(): void {
    this.run(this.api.allocate(this.allocateForm), () => (this.allocateForm = null));
  }

  openReturn(outcome: 'returned' | 'lost'): void {
    this.returnForm = { allocationId: this.current.id, outcome, returnedOn: this.today, condition: this.asset.condition, notes: '', recoveryAmount: null };
  }

  saveReturn(): void {
    this.run(this.api.receiveReturn(this.returnForm), () => (this.returnForm = null));
  }

  openMaint(): void {
    this.maintForm = { assetId: this.id, type: 'repair', description: '', vendor: '', startDate: this.today };
  }

  saveMaint(): void {
    this.run(this.api.openMaintenance(this.maintForm), () => {
      this.maintForm = null;
      this.tab = 'maintenance';
    });
  }

  openClose(m: any): void {
    this.closeForm = { id: m.id, endDate: this.today, cost: null, conditionAfter: this.asset.condition, notes: '' };
  }

  saveClose(): void {
    this.run(this.api.closeMaintenance(this.closeForm), () => (this.closeForm = null));
  }

  openStatus(status: string): void {
    this.statusForm = { status, note: '' };
  }

  saveStatus(): void {
    this.run(this.api.setStatus(this.id, this.statusForm.status, this.statusForm.note), () => (this.statusForm = null));
  }
}
